"""
Database Module for UPI Sentinel AI.
Implements robust SQLite persistent storage for:
- Live ML model predictions
- Audit ledger & historical investigations
- Sender behavioral transaction history lookup
- Separation of genuine ML predictions from dataset ground-truth labels
"""

import os
import sqlite3
import json
import datetime
from typing import Dict, Any, List, Optional, Tuple
import pandas as pd

DB_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'data')
DB_PATH = os.path.join(DB_DIR, 'upi_sentinel.db')

def get_connection() -> sqlite3.Connection:
    os.makedirs(DB_DIR, exist_ok=True)
    conn = sqlite3.connect(DB_PATH, timeout=10.0)
    conn.row_factory = sqlite3.Row
    return conn

def init_db():
    """Initializes tables if they do not exist."""
    with get_connection() as conn:
        cursor = conn.cursor()
        
        # 1. Predictions table (Live ML predictions generated by active models)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS predictions (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            transaction_id TEXT UNIQUE NOT NULL,
            timestamp TEXT NOT NULL,
            sender_id TEXT NOT NULL,
            receiver_id TEXT NOT NULL,
            amount REAL NOT NULL,
            transaction_type TEXT NOT NULL,
            hour_of_day INTEGER DEFAULT 12,
            fraud_probability REAL,
            anomaly_score REAL,
            risk_score REAL NOT NULL,
            risk_category TEXT NOT NULL,
            algorithm_used TEXT NOT NULL,
            model_version TEXT NOT NULL,
            prediction_result TEXT NOT NULL,
            top_reason TEXT,
            all_reasons_json TEXT,
            investigation_status TEXT DEFAULT 'CLEARED',
            is_cold_start INTEGER DEFAULT 0,
            created_at TEXT NOT NULL
        );
        """)

        # Indices for rapid querying & search
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_pred_sender ON predictions(sender_id);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_pred_risk_score ON predictions(risk_score);")
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_pred_timestamp ON predictions(timestamp);")

        # 2. Historical dataset records table (Ground-truth labels from uploaded datasets)
        cursor.execute("""
        CREATE TABLE IF NOT EXISTS dataset_records (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            transaction_id TEXT UNIQUE NOT NULL,
            timestamp TEXT,
            sender_id TEXT,
            receiver_id TEXT,
            amount REAL,
            transaction_type TEXT,
            is_fraud INTEGER,
            dataset_name TEXT,
            uploaded_at TEXT
        );
        """)
        cursor.execute("CREATE INDEX IF NOT EXISTS idx_ds_sender ON dataset_records(sender_id);")

        conn.commit()

def save_prediction_record(record: Dict[str, Any]) -> int:
    """Inserts a genuine ML prediction into persistent SQLite storage."""
    init_db()
    with get_connection() as conn:
        cursor = conn.cursor()
        now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

        reasons_json = json.dumps(record.get('all_reasons', []))

        cursor.execute("""
        INSERT OR REPLACE INTO predictions (
            transaction_id, timestamp, sender_id, receiver_id, amount,
            transaction_type, hour_of_day, fraud_probability, anomaly_score,
            risk_score, risk_category, algorithm_used, model_version,
            prediction_result, top_reason, all_reasons_json,
            investigation_status, is_cold_start, created_at
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            str(record.get('transaction_id')),
            str(record.get('timestamp', now_str)),
            str(record.get('sender_id', 'unknown@upi')),
            str(record.get('receiver_id', 'unknown@upi')),
            float(record.get('amount', 0.0)),
            str(record.get('transaction_type', 'PAYMENT')),
            int(record.get('hour_of_day', 12)),
            float(record['fraud_probability']) if record.get('fraud_probability') is not None else None,
            float(record['anomaly_score']) if record.get('anomaly_score') is not None else None,
            float(record.get('risk_score', 0.0)),
            str(record.get('risk_category', 'Low Risk')),
            str(record.get('algorithm_used', 'Random Forest')),
            str(record.get('model_version', 'v1.0')),
            str(record.get('prediction_result', 'Normal / Legitimate')),
            str(record.get('top_reason', 'Verified User Pattern')),
            reasons_json,
            str(record.get('investigation_status', 'CLEARED')),
            int(record.get('is_cold_start', 0)),
            now_str
        ))
        conn.commit()
        return cursor.lastrowid

def query_predictions(
    risk_category: Optional[str] = None,
    min_amount: Optional[float] = None,
    search_query: Optional[str] = None,
    page: int = 1,
    page_size: int = 25
) -> Tuple[List[Dict[str, Any]], int]:
    """Queries persistent predictions with filtering, pagination, and text search."""
    init_db()
    with get_connection() as conn:
        cursor = conn.cursor()
        where_clauses = []
        params = []

        if risk_category and risk_category not in ["All", "", "all"]:
            cat_clean = risk_category.strip().lower()
            if "very high" in cat_clean or "critical" in cat_clean:
                where_clauses.append("risk_score > 80.0")
            elif "high" in cat_clean:
                where_clauses.append("risk_score > 60.0 AND risk_score <= 80.0")
            elif "medium" in cat_clean:
                where_clauses.append("risk_score > 30.0 AND risk_score <= 60.0")
            elif "low" in cat_clean:
                where_clauses.append("risk_score <= 30.0")

        if min_amount is not None and min_amount > 0:
            where_clauses.append("amount >= ?")
            params.append(min_amount)

        if search_query and search_query.strip():
            sq = f"%{search_query.strip().lower()}%"
            where_clauses.append("(LOWER(transaction_id) LIKE ? OR LOWER(sender_id) LIKE ? OR LOWER(receiver_id) LIKE ?)")
            params.extend([sq, sq, sq])

        where_str = (" WHERE " + " AND ".join(where_clauses)) if where_clauses else ""

        # Count total matched
        cursor.execute(f"SELECT COUNT(*) as total FROM predictions{where_str}", params)
        total_count = cursor.fetchone()['total']

        # Paginated fetch
        offset = (page - 1) * page_size
        query_sql = f"""
        SELECT * FROM predictions{where_str}
        ORDER BY id DESC
        LIMIT ? OFFSET ?
        """
        cursor.execute(query_sql, params + [page_size, offset])
        rows = cursor.fetchall()

        results = [dict(row) for row in rows]
        return results, total_count

def get_sender_behavioral_history(sender_id: str) -> Dict[str, Any]:
    """
    Looks up sender's historical records across both live predictions and ingested dataset.
    Returns calculated historical behavioral statistics.
    """
    init_db()
    records = []
    with get_connection() as conn:
        cursor = conn.cursor()
        
        # From predictions
        cursor.execute("""
        SELECT timestamp, amount, receiver_id
        FROM predictions
        WHERE sender_id = ?
        ORDER BY timestamp ASC
        """, (sender_id,))
        for r in cursor.fetchall():
            records.append({'timestamp': r['timestamp'], 'amount': r['amount'], 'receiver_id': r['receiver_id']})

        # From dataset_records
        cursor.execute("""
        SELECT timestamp, amount, receiver_id
        FROM dataset_records
        WHERE sender_id = ?
        ORDER BY timestamp ASC
        """, (sender_id,))
        for r in cursor.fetchall():
            records.append({'timestamp': r['timestamp'], 'amount': r['amount'], 'receiver_id': r['receiver_id']})

    if not records:
        return {
            "found": False,
            "tx_count": 0,
            "avg_amount": 0.0,
            "known_recipients": [],
            "last_tx_time": None
        }

    amts = [float(r['amount']) for r in records]
    recipients = list(set([str(r['receiver_id']) for r in records if r.get('receiver_id')]))
    
    return {
        "found": True,
        "tx_count": len(records),
        "avg_amount": float(sum(amts) / len(amts)),
        "known_recipients": recipients,
        "last_tx_time": records[-1]['timestamp']
    }

def get_prediction_summary_kpis() -> Dict[str, Any]:
    """Calculates KPI statistics from genuine stored live predictions."""
    init_db()
    with get_connection() as conn:
        cursor = conn.cursor()
        cursor.execute("""
        SELECT 
            COUNT(*) as total_predictions,
            COALESCE(SUM(CASE WHEN risk_score > 60.0 THEN 1 ELSE 0 END), 0) as fraud_or_high_risk,
            COALESCE(SUM(CASE WHEN risk_score <= 30.0 THEN 1 ELSE 0 END), 0) as legitimate_count,
            COALESCE(SUM(CASE WHEN risk_score > 30.0 AND risk_score <= 60.0 THEN 1 ELSE 0 END), 0) as medium_risk_count,
            COALESCE(SUM(CASE WHEN risk_score > 60.0 AND risk_score <= 80.0 THEN 1 ELSE 0 END), 0) as high_risk_count,
            COALESCE(SUM(CASE WHEN risk_score > 80.0 THEN 1 ELSE 0 END), 0) as critical_risk_count,
            COALESCE(AVG(amount), 0.0) as avg_amount
        FROM predictions
        """)
        row = cursor.fetchone()
        return dict(row) if row else {}

# Initialize DB on module load
init_db()
